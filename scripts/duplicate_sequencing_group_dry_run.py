def split_gs_path(path: str) -> tuple[str, str]:
    """Splits gs://bucket/name into (bucket, name)"""
    bucket, _, name = path.removeprefix('gs://').partition('/')
    return bucket, name


def get_blob(
    client: storage.Client, path: str, billing_project: str | None
) -> storage.Blob | None:
    """Returns the blob with its metadata loaded, or None if it does not exist"""
    bucket_name, name = split_gs_path(path)
    return client.bucket(bucket_name, user_project=billing_project).get_blob(name)


def peek_text(blob: storage.Blob) -> str:
    """Reads the start of a file, decompressing (b)gzip members if needed"""
    data = blob.download_as_bytes(start=0, end=min(PEEK_BYTES, blob.size) - 1)
    if not data.startswith(b'\x1f\x8b'):
        return data.decode(errors='replace')

    chunks = []
    while data:
        decompressor = zlib.decompressobj(zlib.MAX_WBITS | 16)
        try:
            chunks.append(decompressor.decompress(data))
        except zlib.error:
            break
        if not decompressor.eof:
            break  # final member truncated by the range read
        data = decompressor.unused_data
    return b''.join(chunks).decode(errors='replace')


