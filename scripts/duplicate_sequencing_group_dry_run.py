def glob_bucket(
    session: AuthorizedSession,
    bucket_name: str,
    pattern: str,
    billing_project: str | None,
) -> list[tuple[str, int]] | None:
    """
    Lists (name, size) of objects matching a glob, or None without list access.
    Calls the JSON API directly, as older google-cloud-storage lacks match_glob.
    """
    url = f'https://storage.googleapis.com/storage/v1/b/{bucket_name}/o'
    params = {'matchGlob': pattern, 'fields': 'items(name,size),nextPageToken'}
    if billing_project:
        params['userProject'] = billing_project
    items: list[tuple[str, int]] = []
    while True:
        response = session.get(url, params=params)
        if response.status_code in (HTTPStatus.FORBIDDEN, HTTPStatus.NOT_FOUND):
            return None
        response.raise_for_status()
        body = response.json()
        items.extend((i['name'], int(i['size'])) for i in body.get('items', []))
        if not (token := body.get('nextPageToken')):
            return items
        params['pageToken'] = token


def scan_for_uncovered_files(
    args: argparse.Namespace, planned_sources: set[str], report: Report
) -> None:
    """Globs the source buckets for SG files the script would not copy"""
    source_bucket, _ = bucket_names(args)
    section(f'6. OTHER FILES CONTAINING {args.original_sg_id} (not copied)')
    credentials, _ = google.auth.default(scopes=[GCS_READ_SCOPE])
    session = AuthorizedSession(credentials)
    for bucket_name in [
        source_bucket,
        f'{source_bucket}-analysis',
        f'{source_bucket}-web',
    ]:
        items = glob_bucket(
            session, bucket_name, f'**{args.original_sg_id}**', args.billing_project
        )
        if items is None:
            report.issue(f'no list access to gs://{bucket_name}')
            continue
        paths = [(f'gs://{bucket_name}/{name}', size) for name, size in items]
        uncovered = [(p, size) for p, size in paths if p not in planned_sources]
        print(
            f'\n    gs://{bucket_name}: {len(paths)} matches, {len(uncovered)} not copied'
        )
        for path, size in uncovered:
            label = secondary_label(path, planned_sources)
            print(f'        {label:<24} {human_size(size):>10}  {path}')
            if label == 'NOT COPIED':
                report.uncovered.append(path)
    if report.uncovered:
        report.issue(
            f'{len(report.uncovered)} files containing {args.original_sg_id} are not '
            'copied (see section 6)'
        )


def secondary_label(path: str, planned_sources: set[str]) -> str:
    """Labels index / checksum files that belong to a copied file"""
    for suffix, regenerated in SECONDARY_SUFFIXES.items():
        if path.endswith(suffix) and path.removesuffix(suffix) in planned_sources:
            return 'index (regenerated)' if regenerated else 'index (NOT made)'
    return 'NOT COPIED'


