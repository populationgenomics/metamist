def describe_handler(source: str, dest: str) -> str:
    """Mirrors the dispatch in dsg.reheader_analysis_files_in_batch"""
    if dsg.file_is_binary(source):
        return 'plain copy, binary (runs locally in the driver)'
    if source.endswith('.somalier'):
        return 'somalier byte rewrite (runs locally in the driver)'
    if dsg.file_reheaderable(source):
        tool = 'samtools' if dest.endswith('.cram') else 'bcftools'
        return f'{tool} reheader + regenerate index'
    if source.endswith('.gz'):
        column = dsg.file_gatk_check(dest)
        if not column:
            return 'bgzip + sed find/replace'
        return f'bgzip + awk set column {column} + regenerate .tbi'
    return 'sed find/replace'


Check = tuple[bool, str]


def check_somalier(blob: storage.Blob, sg_id: str) -> Check:
    """Checks the sample ID in a binary somalier file header"""
    data = blob.download_as_bytes(start=0, end=min(260, blob.size) - 1)
    found = data[2 : 2 + data[1]].decode(errors='replace')
    if found != sg_id:
        return (
            False,
            f'somalier sample ID is {found!r}, expected {sg_id!r} (will raise)',
        )
    return True, f'somalier sample ID is {found}'


def check_vcf(blob: storage.Blob, sg_id: str) -> Check:
    """Checks the #CHROM line holds exactly the original SG ID"""
    chrom_lines = [
        line for line in peek_text(blob).splitlines() if line.startswith('#CHROM')
    ]
    if not chrom_lines:
        return False, f'#CHROM line not found in first {human_size(PEEK_BYTES)}'
    samples = chrom_lines[0].split('\t')[9:]
    if samples != [sg_id]:
        return False, f'VCF samples are {samples}, expected [{sg_id!r}]'
    return True, f'#CHROM sample is {sg_id}'


def check_gatk_evidence(blob: storage.Blob, sg_id: str, column: int) -> Check:
    """Checks the SG ID is in the column the awk command overwrites"""
    lines = [line for line in peek_text(blob).splitlines() if line.strip()]
    if not lines:
        return False, 'could not read any lines'
    fields = lines[0].split('\t')
    if len(fields) < column or fields[column - 1] != sg_id:
        return False, f'column {column} of first line is not {sg_id}: {fields}'
    return True, f'column {column} is {sg_id}'


def check_contents(
    blob: storage.Blob, source: str, dest: str, sg_id: str
) -> Check | None:
    """Checks the SG ID is where the reheader commands expect it, if checkable"""
    if not blob.size:
        return False, 'file is empty'
    if source.endswith('.somalier'):
        return check_somalier(blob, sg_id)
    if dsg.file_reheaderable(source) and not source.endswith('.cram'):
        return check_vcf(blob, sg_id)
    if column := dsg.file_gatk_check(dest):
        return check_gatk_evidence(blob, sg_id, column)
    return None


