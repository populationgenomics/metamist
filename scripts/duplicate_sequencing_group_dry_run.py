def bucket_names(args: argparse.Namespace) -> tuple[str, str]:
    """Returns the (source, destination) main bucket names the script would use"""
    return dsg.get_bucket_names(
        args.source_dataset, args.new_dataset, args.access_level
    )


def find_unmatched_templates(
    client: storage.Client, args: argparse.Namespace
) -> list[str]:
    """Returns the unrecorded file paths with no matching files for this SG"""
    source_bucket, _ = bucket_names(args)
    unmatched = []
    for template in dsg.UNRECORDED_ANALYSIS_FILES + dsg.UNRECORDED_ANALYSIS_FOLDERS:
        path = template.format(bucket_name=source_bucket, sg_id=args.original_sg_id)
        if not dsg.resolve_source_paths(client, path, args.billing_project):
            unmatched.append(path)
    return unmatched


def inspect_files(
    client: storage.Client,
    plan: list[FileCopy],
    sg_id: str,
    args: argparse.Namespace,
) -> None:
    """Fills in existence, size and storage class, and checks file contents"""
    for copy in plan:
        try:
            blob = get_blob(client, copy.source, args.billing_project)
        except Forbidden:
            copy.notes.append('NO READ ACCESS')
            continue
        if blob is None:
            continue
        copy.size = blob.size
        copy.storage_class = blob.storage_class
        if args.reuse_sequencing_group_id and get_blob(
            client, copy.dest, args.billing_project
        ):
            copy.notes.append('destination exists: script will SKIP this file')
        if args.skip_content_checks:
            continue
        if result := check_contents(blob, copy.source, copy.dest, sg_id):
            passed, message = result
            if passed:
                copy.checked = message
            else:
                copy.notes.append(message)


def print_plan(title: str, plan: list[FileCopy], report: Report) -> None:
    """Prints the files that would be copied"""
    section(title)
    for copy in plan:
        print(
            f'\n    [COPY] {human_size(copy.size):>10}  '
            f'{copy.storage_class or "":<9} {copy.handler}'
        )
        print(f'        from {copy.source}')
        print(f'        to   {copy.dest}')
        if copy.checked:
            print(f'        check OK: {copy.checked}')
        for note in copy.notes:
            report.issue(f'{copy.source}: {note}')


def to_plan(moves: list, origin: str) -> list[FileCopy]:
    """Converts the script's (source, destination) pairs to FileCopy entries"""
    return [
        FileCopy(str(src), str(dst), origin, describe_handler(str(src), str(dst)))
        for src, dst in moves
    ]


