#!/usr/bin/env python3

r"""
Read-only dry run of duplicate_sequencing_group.py.

Reports what the duplication script would do for a given sequencing group,
without creating any Metamist records, writing any files, or submitting a batch:

1. Validates the participant / sample IDs against the new dataset, and previews
    the SampleUpsert payload that would create the new sequencing group.
2. Inventories every analysis on the original SG, marking which are copied and
    why the rest are skipped.
3. Resolves the recorded and unrecorded files to copy, checking each exists, its
    size and storage class, and which reheader method would be used.
4. Peeks inside somalier, VCF and GATK-SV evidence files to check that the SG ID
    sits where the reheader commands expect it.
5. Optionally scans the source buckets for any other files containing the SG ID
    that the script would not copy.

The script's own constants and read-only functions are imported so this stays in
sync with it. Needs Metamist auth and GCS read access to the source buckets, e.g.

    python3 scripts/duplicate_sequencing_group_dry_run.py \
        <SG_ID> <source-dataset> <new-dataset> \
        --new_sample_external_id <SAMPLE_EXT_ID> \
        --new_participant_id <PARTICIPANT_EXT_ID>
"""

