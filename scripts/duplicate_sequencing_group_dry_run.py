async def check_new_dataset(args: argparse.Namespace, report: Report) -> None:
    """Checks the participant / sample IDs and existing duplicates"""
    section(f'1. NEW DATASET: {args.new_dataset}')
    response = await query_async(NEW_DATASET_QUERY, {'dataset': args.new_dataset})
    participants = response['project']['participants']
    print(f'    {len(participants)} participants in {args.new_dataset}')

    for sg in response['project']['sequencingGroups']:
        if (sg['meta'] or {}).get(
            'original_sequencing_group_id'
        ) == args.original_sg_id:
            report.issue(
                f'{sg["id"]} in {args.new_dataset} is already a duplicate of '
                f'{args.original_sg_id} - running again would create a second copy'
            )

    if not args.new_sample_external_id and not args.reuse_sequencing_group_id:
        report.issue(
            '--new_sample_external_id not given: creating the sample will fail '
            "('Sample must have primary external_id')"
        )

    for label, wanted in [
        ('participant', args.new_participant_id),
        ('sample', args.new_sample_id or args.new_sample_external_id),
    ]:
        if wanted:
            print(f'    {label} {wanted!r}: {find_entity(participants, label, wanted)}')

    if not (args.new_sample_id or args.new_participant_id):
        print('    No participant/sample ID given: new sample will have no participant')
        return

    try:
        participant_id, sample_id = dsg.validate_ids(
            args.new_participant_id,
            args.new_sample_id,
            args.new_sample_external_id,
            participants,
        )
    except ValueError as e:
        report.issue(
            f'validate_ids() raises: {e} The script stops here, before creating '
            'anything. It cannot create a new participant, only attach to an existing one.'
        )
        return

    print(
        f'    validate_ids() -> participant_id={participant_id}, sample_id={sample_id}'
    )
    if sample_id:
        print('    New SG will be added to the EXISTING sample above')
    else:
        print('    A NEW sample will be created under the existing participant')


def find_entity(participants: list[dict], label: str, wanted: str) -> str:
    """Describes where a participant / sample ID was found in the dataset"""
    for participant in participants:
        if label == 'participant':
            if wanted in participant['externalIds'].values() or wanted == str(
                participant['id']
            ):
                return f'EXISTS (id={participant["id"]})'
            continue
        for sample in participant['samples']:
            if wanted in sample['externalIds'].values() or wanted == sample['id']:
                return f'EXISTS (id={sample["id"]}, participant={participant["id"]})'
    return 'NOT FOUND'


async def preview_sample_upsert(args: argparse.Namespace, report: Report) -> None:
    """Prints the SampleUpsert the script would send"""
    section('2. SAMPLE UPSERT PAYLOAD')
    if args.reuse_sequencing_group_id:
        print(f'    Skipped: reusing existing SG {args.reuse_sequencing_group_id}')
        return
    try:
        upsert = await dsg.get_sample_upsert(
            args.source_dataset,
            args.original_sg_id,
            args.new_sample_external_id,
        )
    except ValueError as e:
        report.issue(f'get_sample_upsert() raises: {e}')
        return

    sg = upsert.sequencing_groups[0]
    print(f'    sample.external_ids : {upsert.external_ids}')
    print(f'    sample.type         : {getattr(upsert, "type", None)}')
    print(f'    sg.type/technology  : {sg.type} / {sg.technology} / {sg.platform}')
    print(f'    sg.meta             : {sg.meta}')
    print(f'    assays              : {len(sg.assays)}')
    for assay in sg.assays:
        print(f'      - {assay.type}: meta keys {sorted(assay.meta)}')
        reads = str(assay.meta.get('reads', ''))
        if args.source_dataset in reads:
            print(
                f'        reads still point at {args.source_dataset} buckets '
                '(meta is copied verbatim)'
            )


