async def fetch_original_sg(args: argparse.Namespace, report: Report) -> dict | None:
    """Fetches the original SG with all its analyses, active or archived"""
    for active_only in (True, False):
        response = await query_async(
            SG_INVENTORY_QUERY,
            {
                'sgId': args.original_sg_id,
                'dataset': args.source_dataset,
                'activeOnly': active_only,
            },
        )
        sgs = response['project']['sequencingGroups']
        if sgs and active_only:
            return sgs[0]
        if sgs:
            report.issue(
                f'{args.original_sg_id} is ARCHIVED - the script only duplicates '
                'active SGs and will stop'
            )
            return sgs[0]
    report.issue(f'{args.original_sg_id} not found in {args.source_dataset}')
    return None


def analysis_decision(analysis: dict) -> str:
    """Mirrors the GraphQL filters and dsg.analysis_skip_reason"""
    if analysis['status'] != 'COMPLETED':
        return f'skip: status {analysis["status"]}'
    if analysis['type'] not in dsg.ANALYSIS_TYPES:
        return 'skip: type not in ANALYSIS_TYPES'
    if reason := dsg.analysis_skip_reason(analysis):
        return f'skip: {reason}'[:34]
    return 'COPY'


def print_analysis_inventory(
    sg: dict, args: argparse.Namespace, report: Report
) -> None:
    """Prints per-SG and copied analyses in full, and collapses skipped cohort ones"""
    section(f'3. ANALYSES ON {args.original_sg_id} ({len(sg["analyses"])} total)')
    print(
        f'    Copied: {dsg.ANALYSIS_TYPES}, COMPLETED, single-SG, '
        'sv only GatherSampleEvidence\n'
    )
    analyses = sorted(sg['analyses'], key=lambda a: (a['type'], a['id']))
    collapsed: dict[tuple[str, str], list[int]] = {}
    for analysis in analyses:
        decision = analysis_decision(analysis)
        stage = analysis['meta'].get('stage', '')
        n_sgs = len(analysis['sequencingGroups'])
        if decision != 'COPY' and n_sgs > 1:
            collapsed.setdefault((analysis['type'], stage), []).append(n_sgs)
            continue
        print(
            f'    [{decision:<34}] {analysis["id"]:>7} {analysis["type"]:<11} '
            f'{stage:<26} {(analysis["timestampCompleted"] or "")[:10]} sgs={n_sgs}'
        )
        print(f'{"":42}{dsg.analysis_output_path(analysis)}')

    print('\n    Skipped cohort-level analyses (more than one SG):')
    for (analysis_type, stage), sizes in sorted(collapsed.items()):
        print(
            f'        {len(sizes):>3} x {analysis_type:<28} {stage:<40} '
            f'({min(sizes)}-{max(sizes)} SGs)'
        )
    flag_analysis_issues(analyses, args, report)


def flag_analysis_issues(
    analyses: list[dict], args: argparse.Namespace, report: Report
) -> None:
    """Reports copied analyses that look wrong, and per-SG analyses left behind"""
    copied = [a for a in analyses if analysis_decision(a) == 'COPY']
    for analysis in copied:
        if args.source_dataset not in dsg.analysis_output_path(analysis):
            report.issue(
                f'analysis {analysis["id"]} path lacks {args.source_dataset!r}, so the '
                'copy would be written back into the SAME bucket'
            )
    for analysis_type in ('cram', 'gvcf'):
        count = sum(a['type'] == analysis_type for a in copied)
        if count > 1:
            report.issue(f'{count} COMPLETED {analysis_type} analyses will be copied')

    left_behind: dict[str, int] = {}
    for analysis in analyses:
        if (
            analysis_decision(analysis) != 'COPY'
            and len(analysis['sequencingGroups']) == 1
        ):
            left_behind[analysis['type']] = left_behind.get(analysis['type'], 0) + 1
    if left_behind:
        report.issue(
            f'single-SG analysis records NOT recreated for the new SG: {left_behind} '
            '(their files may still be copied via the unrecorded list)'
        )


